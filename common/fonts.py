def list_fonts() -> list[dict[str, str]]:
    return list(FONT_CATALOG)


def find_font(key: str) -> dict[str, str] | None:
    key_l = key.strip().lower()
    for row in FONT_CATALOG:
        if key_l in (
            row["id"].lower(),
            row["label"].lower(),
            row["family"].lower(),
            row["package"].lower(),
        ):
            return row
    return None


def current_monospace() -> str | None:
    if not shutil.which("gsettings"):
        return None
    proc = subprocess.run(
        ["gsettings", "get", "org.gnome.desktop.interface", "monospace-font-name"],
        check=False,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return None
    return proc.stdout.strip().strip("'\"")


def ghostty_config_path() -> Path:
    home = Path(os.environ.get("HOME", "/tmp")).expanduser()
    return home / ".config" / "ghostty" / "config"


def write_ghostty_font(family: str) -> Path | None:
    """Upsert `font-family` in Ghostty config when the config path is usable."""
    dest = ghostty_config_path()
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
    except OSError:
        return None
    existing = dest.read_text(encoding="utf-8") if dest.is_file() else ""
    line = f'font-family = "{family}"'
    if re.search(r"(?m)^\s*font-family\s*=", existing):
        body = re.sub(r"(?m)^\s*font-family\s*=.*$", line, existing, count=1)
    else:
        body = (existing.rstrip() + "\n\n" if existing.strip() else "") + line + "\n"
    dest.write_text(body if body.endswith("\n") else body + "\n", encoding="utf-8")
    return dest


def write_nvim_guifont(family: str, size: int = 11) -> Path | None:
    """Write a small guifont snippet sourced by theme colors when present."""
    home = Path(os.environ.get("HOME", "/tmp")).expanduser()
    dest = home / ".config" / "nvim" / "gnomarchi-font.vim"
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
    except OSError:
        return None
    # Neovim GUI: family:hNN — escape spaces in family
    escaped = family.replace(" ", r"\ ")
    dest.write_text(
        f'" generated by gnomarchi font set\n'
        f"if exists('g:GuiLoaded') || exists('g:neovide') || has('gui_running')\n"
        f"  set guifont={escaped}:h{size}\n"
        f"endif\n",
        encoding="utf-8",
    )
    return dest


def set_monospace(family: str, size: int = 11) -> int:
    """Set GNOME monospace font; also Ghostty font-family + nvim guifont."""
    row = find_font(family)
    name = row["family"] if row else family
    value = f"{name} {size}"
    code = 0
    if not shutil.which("gsettings"):
        print(f"would set monospace-font-name={value}", file=sys.stderr)
    else:
        proc = subprocess.run(
            [
                "gsettings",
                "set",
                "org.gnome.desktop.interface",
                "monospace-font-name",
                value,
            ],
            check=False,
        )
        code = int(proc.returncode)
        if code == 0:
            print(f"monospace → {value}")
    ghostty = write_ghostty_font(name)
    if ghostty is not None:
        print(f"ghostty font-family → {name} ({ghostty})")
    nvim = write_nvim_guifont(name, size)
    if nvim is not None:
        print(f"nvim guifont → {name} ({nvim})")
    return code


def install_font(key: str) -> int:
    row = find_font(key)
    if row is None:
        print(f"error: unknown font: {key}", file=sys.stderr)
        return 1
    pkg = row["package"]
    if not shutil.which("pacman"):
        print(f"error: pacman not found; install {pkg} manually", file=sys.stderr)
        return 1
    print(f"installing {pkg} ({row['label']})…")
    code = subprocess.call(["sudo", "pacman", "-Sy", "--needed", "--noconfirm", pkg])
    if code == 0:
        set_monospace(row["family"])
    return int(code)


def catalog_as_dicts() -> list[dict[str, Any]]:
    current = current_monospace() or ""
    out = []
    for row in FONT_CATALOG:
        item = dict(row)
        item["active"] = row["family"] in current
        out.append(item)
    return out
