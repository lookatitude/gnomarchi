def _hex_rgb(value: str) -> tuple[int, int, int]:
    v = value.lstrip("#")
    if len(v) != 6:
        return (11, 18, 32)
    return int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16)


def _write_png(path: Path, width: int, height: int, colors: dict[str, str]) -> None:
    import struct
    import zlib

    bg = _hex_rgb(colors.get("background", "#0b1220"))
    accent = _hex_rgb(colors.get("accent", "#3d8bfd"))
    surface = _hex_rgb(colors.get("surface", "#121a2b"))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    rows: list[bytes] = []
    for y in range(height):
        row = bytearray()
        ty = y / max(height - 1, 1)
        for x in range(width):
            tx = x / max(width - 1, 1)
            r = int(bg[0] * (1 - tx) + surface[0] * tx)
            g = int(bg[1] * (1 - ty) + surface[1] * ty)
            b = int(bg[2] * (1 - (tx + ty) / 2) + surface[2] * ((tx + ty) / 2))
            if (x - int(width * 0.72)) ** 2 + (y - int(height * 0.28)) ** 2 < (
                height * 0.22
            ) ** 2:
                r = min(255, (r + accent[0]) // 2)
                g = min(255, (g + accent[1]) // 2)
                b = min(255, (b + accent[2]) // 2)
            row += bytes((r, g, b))
        rows.append(b"\x00" + bytes(row))
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
        + chunk(b"IEND", b"")
    )


def video_wallpaper_enabled() -> bool:
    flag = state_dir() / "video-wallpaper"
    return flag.is_file() and flag.read_text(encoding="utf-8").strip() == "on"


def set_video_wallpaper_enabled(on: bool) -> None:
    flag = state_dir() / "video-wallpaper"
    flag.parent.mkdir(parents=True, exist_ok=True)
    flag.write_text("on\n" if on else "off\n", encoding="utf-8")
    if not on:
        _run(["systemctl", "--user", "disable", "--now", "gnomarchi-video-wallpaper.service"])


def _find_pack_video(pack: Path) -> Path | None:
    """Prefer backgrounds/*.mp4 then root wallpaper.mp4/webm."""
    bg = pack / "backgrounds"
    if bg.is_dir():
        for path in sorted(bg.iterdir()):
            if path.is_file() and path.suffix.lower() in {".mp4", ".webm", ".mkv", ".mov"}:
                return path
    for name in ("wallpaper.mp4", "wallpaper.webm"):
        cand = pack / name
        if cand.is_file():
            return cand
    return None


def emit_video_wallpaper(pack: Path) -> Path | None:
    """Stage pack video + mpv user unit; start only when video wallpaper mode is on."""
    video = _find_pack_video(pack)
    if video is None:
        return None
    dest_dir = state_dir() / "wallpapers"
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / f"active{video.suffix.lower()}"
    if video.resolve() != dest.resolve():
        shutil.copy2(video, dest)
    home = Path(os.environ.get("HOME", "/tmp")).expanduser()
    unit_dir = home / ".config" / "systemd" / "user"
    unit_dir.mkdir(parents=True, exist_ok=True)
    unit = unit_dir / "gnomarchi-video-wallpaper.service"
    mpv = shutil.which("mpv") or "mpv"
    unit.write_text(
        "[Unit]\nDescription=gnomarchi video wallpaper (mpv)\n"
        "PartOf=graphical-session.target\n"
        "[Service]\nType=simple\n"
        "ExecStart="
        f"{mpv} --loop=inf --no-audio --fs --no-border --no-osc "
        f"--really-quiet --hwdec=auto --panscan=1.0 {dest}\n"
        "Restart=on-failure\nRestartSec=2\n"
        "[Install]\nWantedBy=default.target\n",
        encoding="utf-8",
    )
    if video_wallpaper_enabled():
        _run(["systemctl", "--user", "daemon-reload"])
        _run(["systemctl", "--user", "enable", "--now", "gnomarchi-video-wallpaper.service"])
    return dest


def emit_wallpaper(pack: Path, colors: dict[str, str]) -> Path:
    dest_dir = state_dir() / "wallpapers"
    dest_dir.mkdir(parents=True, exist_ok=True)
    # Stage/start video unit when mode is on (stills still used as GSettings underlay).
    emit_video_wallpaper(pack)
    # Prefer ported pack stills (CREDITS required by validate_theme).
    try:
        from theme.backgrounds import list_pack_stills

        stills = list_pack_stills(pack)
    except Exception:
        stills = []
    pack_wall = pack / "wallpaper.png"
    candidates: list[Path] = []
    if pack_wall.is_file():
        candidates.append(pack_wall)
    candidates.extend(stills)
    for wall in pack.glob("wallpaper.*"):
        if (
            wall.is_file()
            and wall.suffix.lower() not in {".mp4", ".webm", ".mkv", ".mov"}
            and wall not in candidates
        ):
            candidates.append(wall)
    if candidates:
        chosen = candidates[0]
        dest = dest_dir / f"active{chosen.suffix.lower()}"
        for old in dest_dir.glob("active.*"):
            if old != dest and old.suffix.lower() not in {".mp4", ".webm", ".mkv", ".mov"}:
                old.unlink(missing_ok=True)
        shutil.copy2(chosen, dest)
        return dest
    dest = dest_dir / "active.png"
    _write_png(dest, 1920, 1080, colors)
    return dest


def accent_gsettings_name(hex_color: str) -> str:
    """Map a pack accent hex to the nearest GNOME Shell accent-color enum value."""
    # Reference centroids for org.gnome.desktop.interface accent-color
    refs: dict[str, tuple[float, float, float]] = {
        "blue": (0.45, 0.55, 0.90),
        "teal": (0.20, 0.70, 0.65),
        "green": (0.30, 0.75, 0.40),
        "yellow": (0.95, 0.80, 0.25),
        "orange": (0.95, 0.55, 0.20),
        "red": (0.90, 0.25, 0.25),
        "pink": (0.90, 0.40, 0.65),
        "purple": (0.60, 0.35, 0.85),
        "slate": (0.45, 0.50, 0.55),
    }

    def _rgb(h: str) -> tuple[float, float, float]:
        s = h.strip().lstrip("#")
        if len(s) == 3:
            s = "".join(c * 2 for c in s)
        if len(s) != 6:
            return refs["blue"]
        try:
            return (int(s[0:2], 16) / 255.0, int(s[2:4], 16) / 255.0, int(s[4:6], 16) / 255.0)
        except ValueError:
            return refs["blue"]

    r, g, b = _rgb(hex_color)
    best = "blue"
    best_d = 1e9
    for name, (rr, gg, bb) in refs.items():
        d = (r - rr) ** 2 + (g - gg) ** 2 + (b - bb) ** 2
        if d < best_d:
            best_d = d
            best = name
    return best


def emit_gsettings(wallpaper: Path, colors: dict[str, str]) -> None:
    if not shutil.which("gsettings"):
        return
    uri = wallpaper.resolve().as_uri()
    accent = accent_gsettings_name(colors.get("accent", colors.get("blue", "#7aa2f7")))
    scheme = (
        "prefer-light"
        if str(colors.get("mode", "dark")).lower() in {"light", "latte"}
        else "prefer-dark"
    )
    _run(["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", scheme])
    _run(["gsettings", "set", "org.gnome.desktop.interface", "accent-color", accent])
    _run(["gsettings", "set", "org.gnome.desktop.background", "picture-uri", uri])
    _run(["gsettings", "set", "org.gnome.desktop.background", "picture-uri-dark", uri])
    _run(["gsettings", "set", "org.gnome.desktop.background", "picture-options", "zoom"])
    _run(
        [
            "gsettings",
            "set",
            "org.gnome.desktop.background",
            "primary-color",
            colors.get("background", "#0b1220"),
        ]
    )


