USER_THEME_UUID = "user-theme@gnome-shell-extensions.gcampax.github.com"


def enable_user_themes_extension() -> None:
    """Enable the Arch `gnome-shell-extensions` user-themes UUID when possible."""
    if not shutil.which("gnome-extensions"):
        return
    _run(["gnome-extensions", "enable", USER_THEME_UUID])
    # Also merge into gsettings enabled-extensions for sessions where
    # gnome-extensions CLI races with Shell.
    if not shutil.which("gsettings"):
        return
    proc = _run(["gsettings", "get", "org.gnome.shell", "enabled-extensions"])
    raw = (proc.stdout or "").strip() if proc else ""
    if not raw:
        return
    import ast

    text = raw[4:] if raw.startswith("@as ") else raw
    try:
        enabled = list(ast.literal_eval(text))
    except (SyntaxError, ValueError):
        return
    if USER_THEME_UUID not in enabled:
        enabled.append(USER_THEME_UUID)
        _run(
            [
                "gsettings",
                "set",
                "org.gnome.shell",
                "enabled-extensions",
                str(enabled),
            ]
        )


