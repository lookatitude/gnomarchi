def _run(argv: list[str]) -> subprocess.CompletedProcess[str] | None:
    try:
        return subprocess.run(
            argv, check=False, capture_output=True, text=True, timeout=15
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None


def emit_gtk_css(pack: Path, colors: dict[str, str]) -> Path:
    home = Path(os.environ.get("HOME", "/tmp")).expanduser()
    src = pack / "gtk.css"
    if src.is_file():
        css = src.read_text(encoding="utf-8")
    else:
        bg = colors.get("background", "#0b1220")
        fg = colors.get("foreground", "#e8eef7")
        accent = colors.get("accent", "#3d8bfd")
        css = (
            f"@define-color window_bg_color {bg};\n"
            f"@define-color window_fg_color {fg};\n"
            f"@define-color accent_bg_color {accent};\n"
            f"@define-color accent_fg_color {bg};\n"
        )
    banner = "/* generated by gnomarchi theme set — do not edit */\n"
    written: list[Path] = []
    for rel in ("gtk-4.0/gtk.css", "gtk-3.0/gtk.css"):
        dest = home / ".config" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(banner + css, encoding="utf-8")
        written.append(dest)
    return written[0]


def emit_ghostty(colors: dict[str, str]) -> Path:
    """Emit Ghostty colors from Omarchy-style ghostty.conf.tpl when present."""
    home = Path(os.environ.get("HOME", "/tmp")).expanduser()
    dest = home / ".config" / "ghostty" / "config"
    dest.parent.mkdir(parents=True, exist_ok=True)
    tpl_path = REPO_ROOT / "theme" / "ghostty.conf.tpl"
    ctx = {
        **colors,
        "selection_background": colors.get("selection", colors.get("accent", "#3d8bfd")),
        "selection_foreground": colors.get("background", "#0b1220"),
        "bright_foreground": colors.get("bright_foreground", colors.get("foreground")),
    }

    def render(tpl: str) -> str:
        def repl(m: re.Match[str]) -> str:
            key = m.group(1).strip()
            return ctx.get(key, m.group(0))

        return re.sub(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}", repl, tpl)

    if tpl_path.is_file():
        body = (
            "# generated by gnomarchi theme set (Omarchy ghostty template)\n"
            + render(tpl_path.read_text(encoding="utf-8"))
            + "\nfont-size = 13\nwindow-padding-x = 14\nwindow-padding-y = 12\n"
        )
    else:
        bg = colors.get("background", "#0b1220")
        fg = colors.get("foreground", "#e8eef7")
        accent = colors.get("accent", "#3d8bfd")
        body = f"""\
# generated by gnomarchi theme set
background = {bg}
foreground = {fg}
cursor-color = {accent}
selection-background = {accent}
selection-foreground = {bg}
palette = 0={bg}
palette = 1={colors.get('red', accent)}
palette = 2={colors.get('green', accent)}
palette = 3={colors.get('yellow', accent)}
palette = 4={colors.get('blue', accent)}
palette = 5={colors.get('magenta', accent)}
palette = 6={colors.get('cyan', accent)}
palette = 7={fg}
palette = 8={colors.get('muted', fg)}
palette = 15={fg}
font-size = 13
window-padding-x = 14
window-padding-y = 12
"""
    existing = dest.read_text(encoding="utf-8") if dest.is_file() else ""
    marker = "# generated by gnomarchi theme set"
    if marker in existing:
        head, _, _ = existing.partition(marker)
        dest.write_text(head.rstrip() + "\n\n" + body, encoding="utf-8")
    else:
        dest.write_text(
            (existing.rstrip() + "\n\n" if existing.strip() else "") + body,
            encoding="utf-8",
        )
    return dest


